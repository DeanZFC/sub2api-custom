import { flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { createI18n } from 'vue-i18n'
import ChannelQualityScoreSettings from '../ChannelQualityScoreSettings.vue'
import resources from '@/i18n/locales/en/admin/resources'
import { defaultQualityScoreConfig } from '@/utils/channelQualityScore'
const api = vi.hoisted(() => ({ scoreConfig: vi.fn(), saveScoreConfig: vi.fn() }))
vi.mock('@/api/admin/channelQuality', () => ({ channelQualityAPI: api }))
const mountPanel = () => mount(ChannelQualityScoreSettings, { global: { plugins: [createI18n({ legacy: false, locale: 'en', missingWarn: false, fallbackWarn: false, messages: { en: { admin: resources } } })] } })
beforeEach(() => {
  vi.resetAllMocks()
  api.scoreConfig.mockResolvedValue(defaultQualityScoreConfig(4))
  api.saveScoreConfig.mockImplementation(async config => ({ ...config, version: 5 }))
})
describe('independent quality scoring settings', () => {
  it('starts with sampling explained and standards collapsed, and saves its own versioned settings', async () => {
    const wrapper = mountPanel(); await flushPromises()
    expect(wrapper.get('[data-score-window]').text()).toContain('Last 15 minutes · up to 100 requests')
    expect(wrapper.get('[data-score-advanced]').attributes('open')).toBeUndefined()
    expect(api.saveScoreConfig).not.toHaveBeenCalled()
    await wrapper.get('[data-score-field="duration.weight"]').setValue(15)
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(api.saveScoreConfig).toHaveBeenCalledWith(expect.objectContaining({ version: 4, duration: { weight: 15, good: 10000, bad: 120000 } }))
    expect(wrapper.get('[role="status"]').text()).toBe('Scoring settings saved')
    wrapper.unmount()
  })
  it('reveals invalid standards and rejects reversed cache scales and impossible samples', async () => {
    const wrapper = mountPanel(); await flushPromises()
    await wrapper.get('[data-score-field="min_samples"]').setValue(101)
    expect(wrapper.get('[data-save-score]').attributes('disabled')).toBeDefined()
    expect(wrapper.get('[data-score-advanced]').attributes('open')).toBeDefined()
    await wrapper.get('form').trigger('submit')
    expect(api.saveScoreConfig).not.toHaveBeenCalled()
    await wrapper.get('[data-score-field="min_samples"]').setValue(20)
    await wrapper.get('[data-score-field="cache_rate.good"]').setValue(0)
    expect(wrapper.text()).toContain('Check Reusable-prefix cache rate (%)')
    await wrapper.get('form').trigger('submit')
    expect(api.saveScoreConfig).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('keeps TPS disabled for old configs, validates higher-is-better, and saves an explicit weight', async () => {
    const oldConfig = defaultQualityScoreConfig(4)
    Reflect.deleteProperty(oldConfig, 'tps')
    api.scoreConfig.mockResolvedValue(oldConfig)
    const wrapper = mountPanel(); await flushPromises()
    expect((wrapper.get('[data-score-field="tps.weight"]').element as HTMLInputElement).value).toBe('0')
    await wrapper.get('[data-score-field="tps.weight"]').setValue(15)
    await wrapper.get('[data-score-field="tps.good"]').setValue(4)
    expect(wrapper.get('[data-save-score]').attributes('disabled')).toBeDefined()
    await wrapper.get('form').trigger('submit')
    expect(api.saveScoreConfig).not.toHaveBeenCalled()
    await wrapper.get('[data-score-field="tps.good"]').setValue(50)
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(api.saveScoreConfig).toHaveBeenCalledWith(expect.objectContaining({ tps: { weight: 15, good: 50, bad: 5 } }))
    wrapper.unmount()
  })

  it('keeps edited values and version on conflict until explicit reload', async () => {
    api.saveScoreConfig.mockRejectedValue({ response: { status: 409 } })
    const wrapper = mountPanel(); await flushPromises()
    await wrapper.get('[data-score-field="max_requests"]').setValue(150)
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(wrapper.text()).toContain('Your edits are preserved')
    expect((wrapper.get('[data-score-field="max_requests"]').element as HTMLInputElement).value).toBe('150')
    api.scoreConfig.mockResolvedValue({ ...defaultQualityScoreConfig(6), max_requests: 200 })
    await wrapper.vm.refresh(); await flushPromises()
    expect((wrapper.get('[data-score-field="max_requests"]').element as HTMLInputElement).value).toBe('150')
    await wrapper.get('[data-score-reload]').trigger('click'); await flushPromises()
    expect((wrapper.get('[data-score-field="max_requests"]').element as HTMLInputElement).value).toBe('200')
    api.saveScoreConfig.mockResolvedValue(defaultQualityScoreConfig(7))
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(api.saveScoreConfig).toHaveBeenLastCalledWith(expect.objectContaining({ version: 6, max_requests: 200 }))
    wrapper.unmount()
  })
  it('restores defaults while retaining the reviewed revision', async () => {
    const wrapper = mountPanel(); await flushPromises()
    await wrapper.get('[data-score-field="error_rate.weight"]').setValue(10)
    await wrapper.get('[data-score-defaults]').trigger('click')
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(api.saveScoreConfig).toHaveBeenCalledWith(defaultQualityScoreConfig(4))
    wrapper.unmount()
  })
})
