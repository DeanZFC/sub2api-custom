const maxInputImages = 4

// QQ nests quotes, combined messages and parallel text/image parts. Bound the
// traversal independently of the webhook body size and treat all parts as data.
func eventParts(e Event) (string, []Attachment) {
	var text strings.Builder
	attachments := append([]Attachment(nil), e.Attachments...)
	remaining := 32
	var visit func([]MessageElement, int)
	visit = func(elements []MessageElement, depth int) {
		if depth > 4 {
			return
		}
		for _, element := range elements {
			if remaining == 0 {
				return
			}
			remaining--
			if text.Len() < 24000 && element.Content != "" {
				_, _ = text.WriteString(limitText(element.Content, 6000))
				_ = text.WriteByte('\n')
			}
			attachments = append(attachments, element.Attachments...)
			visit(element.MsgElements, depth+1)
		}
	}
	visit(e.MsgElements, 0)
	return limitText(strings.TrimSpace(text.String()), 6000), attachments
}

func imageAttachments(attachments []Attachment) []Attachment {
	var images []Attachment
	for _, attachment := range attachments {
		if strings.HasPrefix(strings.ToLower(attachment.ContentType), "image/") {
			images = append(images, attachment)
		}
	}
	return images
}

func (s *Service) chatMessage(ctx context.Context, c Config, e Event, prompt string, ref *botMessageReference) (Message, error) {
	parts, attachments := eventParts(e)
	storedImage, storedAttachments, err := s.referencedImageSources(ctx, c, e, ref)
	if err != nil {
		return Message{}, err
	}
	quotedAttachments := quotedImageAttachments(e)
	if len(quotedAttachments) > 0 {
		// A fresh QQ quote can refresh an expired signed attachment URL. When
		// generated bytes exist, avoid downloading a redundant quoted copy.
		storedAttachments = nil
		if len(storedImage) == 0 {
			storedAttachments = quotedAttachments
		} else {
			quotedURLs := make(map[string]bool)
			for _, a := range quotedAttachments {
				quotedURLs[a.URL] = true
			}
			filtered := attachments[:0]
			for _, a := range attachments {
				if !quotedURLs[a.URL] {
					filtered = append(filtered, a)
				}
			}
			attachments = filtered
		}
	}
	// Number only unique sources so tool indices match the actual image parts.
	uniqueSources := make([]Attachment, 0, len(storedAttachments))
	sourceURLs := make(map[string]bool)
	for _, attachment := range storedAttachments {
		u := attachment.URL
		if strings.HasPrefix(u, "//") {
			u = "https:" + u
		}
		if !sourceURLs[u] {
			sourceURLs[u] = true
			uniqueSources = append(uniqueSources, attachment)
		}
	}
	storedAttachments = uniqueSources
	if parts != "" {
		label := "QQ 消息附带的内容"
		if e.referenceID() != "" || e.MessageType == 103 {
			label = "QQ 消息附带的引用内容"
		}
		prompt = "【" + label + "】\n" + parts + "\n\n【当前消息】\n" + prompt
	}
	if ref != nil {
		quoted := ref.Content
		if ref.Image {
			quoted += "\n（这是一条图片消息，图片内容以本次输入的原图为准。）"
		}
		prompt = "【用户正在回复的机器人消息】\n" + quoted + "\n\n" + prompt
	} else if len(storedAttachments) > 0 {
		prompt = "【用户正在回复的群成员图片】\n原图已附在本次输入中。\n\n" + prompt
	} else if e.referenceID() != "" && parts == "" && len(imageAttachments(attachments)) == 0 {
		prompt = "【引用提示】未找到被引用消息的内容，不要猜测；需要时请用户重新发送。\n\n" + prompt
	}
	message := Message{Role: "user", Content: prompt}
	images := imageAttachments(attachments)
	if len(images) > maxInputImages {
		return Message{}, errors.New("每条消息最多支持 4 张图片，请分开发送。")
	}
	if len(storedImage) > 0 {
		dataURL, err := inputImageDataURL(storedImage)
		if err != nil {
			return Message{}, err
		}
		message.Images = append(message.Images, dataURL)
		message.Content += "\n【图片顺序】第 1 张是明确引用的原图；其余为本次消息附图。"
	} else if len(storedAttachments) > 0 {
		message.Content += fmt.Sprintf("\n【图片顺序】前 %d 张来自明确引用的消息；其余为本次消息附图。", len(storedAttachments))
	}
	images = append(storedAttachments, images...)
	seen := make(map[string]bool)
	total := len(storedImage)
	for _, attachment := range images {
		url := attachment.URL
		if strings.HasPrefix(url, "//") {
			url = "https:" + url
		}
		if seen[url] {
			continue
		}
		seen[url] = true
		if len(message.Images) >= maxInputImages {
			return Message{}, errors.New("每条消息最多支持 4 张图片，请分开发送。")
		}
		if attachment.Size > 10<<20 {
			return Message{}, errors.New("单张图片不能超过 10 MB，请压缩后重发。")
		}
		data, err := s.imageDownload(ctx, url)
		if err != nil {
			return Message{}, errors.New("图片读取失败，请重新发送图片后再试。")
		}
		total += len(data)
		if len(data) > 10<<20 || total > 20<<20 {
			return Message{}, errors.New("图片过大，请压缩或分开发送。")
		}
		dataURL, err := inputImageDataURL(data)
		if err != nil {
			return Message{}, err
		}
		message.Images = append(message.Images, dataURL)
	}
	if ref != nil && ref.Image && len(message.Images) == 0 {
		return Message{}, errors.New("引用的图片已过期或无法读取，请重新发送原图后再试。")
	}
	return message, nil
}

func inputImageDataURL(data []byte) (string, error) {
	if len(data) > 10<<20 {
		return "", errors.New("单张图片不能超过 10 MB，请压缩后重发。")
	}
	mime := http.DetectContentType(data)
	switch mime {
	case "image/jpeg", "image/png", "image/gif", "image/webp":
	default:
		return "", errors.New("图片格式不受支持，请发送 JPEG、PNG、GIF 或 WebP 图片。")
	}
	cfg, _, err := image.DecodeConfig(bytes.NewReader(data))
	if err != nil || cfg.Width < 1 || cfg.Height < 1 || int64(cfg.Width)*int64(cfg.Height) > 40_000_000 {
		return "", errors.New("图片尺寸或内容无效，请压缩后重发。")
	}
	return "data:" + mime + ";base64," + base64.StdEncoding.EncodeToString(data), nil
}
